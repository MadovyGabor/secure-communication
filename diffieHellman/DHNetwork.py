from diffieHellman import DHLogic

def build_init_packet() -> tuple[str, int, int, int]:
    """
    Called by the Initiator: Generates DH parameters and builds the initial DH_INIT packet.
    This can be executed by any node in the network to start a secure handshake.

    Returns:
        tuple: (raw_packet_string, p, g, local_private_key)
    """
    print("[DH Protocol] Generating DH parameters (this might take a few seconds)...")
    p, g = DHLogic.generate_dh_parameters()

    print("[DH Protocol] Generating private key...")
    private_key = DHLogic.generate_private_key(p)

    print("[DH Protocol] Generating public key (A)...")
    public_key = DHLogic.generate_public_key(private_key, g, p)

    # Build the raw string packet to send over the network
    packet = f"DH_INIT:{p}:{g}:{public_key}"
    print("[DH Protocol] DH_INIT packet built successfully. Ready to send.")

    return packet, p, g, private_key


def process_init_packet(message: str) -> tuple[str, int]:
    """
    Called by the Responder: Parses the incoming DH_INIT packet, generates local keys,
    calculates the shared secret, and builds the DH_ACCEPT response.

    Args:
        message (str): The raw DH_INIT packet received from the peer.

    Returns:
        tuple: (response_packet_string, shared_secret)
    """
    print("[DH Protocol] Received DH_INIT packet. Parsing parameters...")

    # Split the message by colons to extract the values
    parts = message.split(":")
    p = int(parts[1])
    g = int(parts[2])
    peer_public_key = int(parts[3])

    print(f"[DH Protocol] Extracted Peer's Public Key: {str(peer_public_key)[:15]}...")

    print("[DH Protocol] Generating local private and public keys...")
    my_private_key = DHLogic.generate_private_key(p)
    my_public_key = DHLogic.generate_public_key(my_private_key, g, p)

    print("[DH Protocol] Calculating the SHARED SECRET (K)...")
    shared_secret = DHLogic.generate_shared_secret(my_private_key, peer_public_key, p)

    # Build the response packet containing this node's public key
    accept_packet = f"DH_ACCEPT:{my_public_key}"
    print("[DH Protocol] DH_ACCEPT packet built successfully. Ready to send.")

    return accept_packet, shared_secret


def process_accept_packet(message: str, p: int, private_key: int) -> int:
    """
    Called by the Initiator: Parses the DH_ACCEPT packet and calculates the final shared secret.

    Args:
        message (str): The raw DH_ACCEPT packet received from the peer.
        p (int): The prime modulus previously generated by this node.
        private_key (int): This node's local private key.

    Returns:
        int: The final calculated shared secret.
    """
    print("[DH Protocol] Received DH_ACCEPT packet. Extracting Peer's Public Key...")

    # Split the message to get the peer's public key
    parts = message.split(":")
    peer_public_key = int(parts[1])

    print(f"[DH Protocol] Extracted Peer's Public Key: {str(peer_public_key)[:15]}...")

    print("[DH Protocol] Calculating the SHARED SECRET (K)...")
    shared_secret = DHLogic.generate_shared_secret(private_key, peer_public_key, p)

    print("[DH Protocol] Handshake complete! Shared secret is ready for encryption.")

    return shared_secret